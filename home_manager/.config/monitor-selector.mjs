#!/usr/bin/env zx

const entries = "Tv on\nTv gaming\nTv off";
const selected = await $`$HOME/.config/wofi-monitor.mjs 250 100 ${entries}`.text();

let state;
if (selected.includes("on"))
    state = "3840x2160@24";
else if (selected.includes("gaming"))
    state = "3840x2160@120"
else if (selected.includes("off"))
    state = "disabled"
else
    process.exit(0)

const file = 
`# auto generated by monitor-selector.mjs. Do not modify!!!
monitor = HDMI-A-2, ${state}, 4480x0, 2`;

await $`echo ${file} > ~/.config/hypr/modules/tv.conf`;
